def rows(ch):
    return G[ch].strip('\n').split('\n')


def build():
    chars = list(G.keys())
    # Lowercase shares the capitals' drawings.
    chars += [c.lower() for c in G if 'A' <= c <= 'Z']
    lines = (len(chars) + COLS - 1) // COLS
    img = Image.new('RGBA', (COLS * CELL, lines * CELL), (0, 0, 0, 0))
    px = img.load()
    grid = []
    for li in range(lines):
        row = chars[li * COLS:(li + 1) * COLS]
        grid.append(''.join(row) + '\u0000' * (COLS - len(row)))
        for ci, ch in enumerate(row):
            r = rows(ch.upper() if ch.upper() in G and ch not in G else ch)
            width = max(len(s) for s in r)
            assert width <= CELL - 2 and len(r) <= CELL - 1, ch
            ox, oy = ci * CELL, li * CELL
            for y, s in enumerate(r):
                for x, c in enumerate(s):
                    if c == '#':
                        px[ox + x, oy + 1 + y] = (255, 255, 255, 255)
            # An invisible pixel one column past the glyph: the advance then leaves a two-pixel
            # gap, which suits two-pixel stems better than vanilla's single pixel.
            px[ox + width, oy] = (255, 255, 255, 1)
    return img, grid


def main():
    img, grid = build()
    tex = os.path.join(ASSETS, 'textures', 'font')
    os.makedirs(tex, exist_ok=True)
    img.save(os.path.join(tex, 'display.png'))
    font = {'providers': [
        {'type': 'space', 'advances': {' ': 5, '‌': 0}},
        {'type': 'bitmap', 'file': 'afterworld:font/display.png', 'height': CELL, 'ascent': 8, 'chars': grid},
        {'type': 'reference', 'id': 'minecraft:include/default'},
    ]}
    os.makedirs(os.path.join(ASSETS, 'font'), exist_ok=True)
    with open(os.path.join(ASSETS, 'font', 'display.json'), 'w', encoding='utf-8') as f:
        json.dump(font, f, indent=2, ensure_ascii=False)
    print('display font:', sum(len(g.rstrip('\u0000')) for g in grid), 'glyphs', img.size)
    if len(sys.argv) > 1:
        preview(sys.argv[1])


def preview(path):
    """Renders sample lines at 4x, the way the arrival draws them."""
    text = ['WHERE DO YOU COME FROM?', 'HOW DO YOU MEET TROUBLE?', 'WHAT LIES WITHIN YOU?',
            'WHAT IS YOUR NAME?', '...AND THE WORLD BEGINS TO', 'REMEMBER YOU.', 'QUICK BROWN FOX: 0123456789 &!',
            '▸ GUILD CARTOGRAPHER  ◆ ◇ ■ □ ↑↓←→']
    s = 4
    img = Image.new('RGB', (1200, 60 + len(text) * 15 * s), (8, 9, 12))
    px = img.load()
    y = 20
    for line in text:
        x = 20
        for ch in line:
            if ch == ' ':
                x += 5 * s
                continue
            r = rows(ch.upper() if ch not in G else ch)
            for j, srow in enumerate(r):
                for i, c in enumerate(srow):
                    if c == '#':
                        for dy in range(s):
                            for dx in range(s):
                                if x + i * s + dx < img.width:
                                    px[x + i * s + dx, y + j * s + dy] = (235, 225, 200)
            x += (max(len(q) for q in r) + 2) * s
        y += 15 * s
    img.save(path)


if __name__ == '__main__':
    main()
