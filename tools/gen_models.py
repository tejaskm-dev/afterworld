#!/usr/bin/env python3
"""Boss models from a single spec: packs UVs, writes Java LayerDefinitions, and paints matching textures."""
import math, os, random, sys
from PIL import Image, ImageDraw
sys.path.insert(0, os.path.dirname(__file__))
from pixel import hexc, mix, shade

HERE = os.path.dirname(os.path.abspath(__file__))
JAVA_OUT = os.path.join(HERE, '..', 'src', 'client', 'java', 'dev', 'afterworld', 'client', 'model', 'gen')
TEX_OUT = os.path.join(HERE, '..', 'src', 'main', 'resources', 'assets', 'afterworld', 'textures', 'entity')

class Box:
    def __init__(self, origin, size, mat, inflate=0.0):
        self.origin, self.size, self.mat, self.inflate = origin, size, mat, inflate
        self.u = self.v = 0

class Part:
    def __init__(self, name, pivot=(0, 0, 0), rot=(0, 0, 0), boxes=(), children=()):
        self.name, self.pivot, self.rot, self.boxes, self.children = name, pivot, rot, list(boxes), list(children)

def all_boxes(part):
    for b in part.boxes:
        yield b
    for c in part.children:
        yield from all_boxes(c)

def uv_size(b):
    w, h, d = (int(math.ceil(s)) for s in b.size)
    return 2 * d + 2 * w, d + h

def pack(root, width):
    boxes = sorted(all_boxes(root), key=lambda b: -uv_size(b)[1])
    x = y = shelf = 0
    for b in boxes:
        bw, bh = uv_size(b)
        if x + bw > width:
            x = 0
            y += shelf
            shelf = 0
        b.u, b.v = x, y
        x += bw
        shelf = max(shelf, bh)
    height = y + shelf
    h = 16
    while h < height:
        h *= 2
    return h

def fmt(f):
    s = ('%.4f' % f).rstrip('0').rstrip('.')
    if s in ('-0', ''):
        s = '0'
    return s + 'F'

def java_part(part, parent_var, out, depth):
    var = part.name + '_p'
    cubes = 'CubeListBuilder.create()'
    for b in part.boxes:
        w, h, d = b.size
        deform = f', new CubeDeformation({fmt(b.inflate)})' if b.inflate else ''
        cubes += f'.texOffs({b.u}, {b.v}).addBox({fmt(b.origin[0])}, {fmt(b.origin[1])}, {fmt(b.origin[2])}, {fmt(w)}, {fmt(h)}, {fmt(d)}{deform})'
    px, py, pz = part.pivot
    rx, ry, rz = part.rot
    pose = f'PartPose.offsetAndRotation({fmt(px)}, {fmt(py)}, {fmt(pz)}, {fmt(rx)}, {fmt(ry)}, {fmt(rz)})'
    out.append(f'\t\tPartDefinition {var} = {parent_var}.addOrReplaceChild("{part.name}", {cubes}, {pose});')
    for c in part.children:
        java_part(c, var, out, depth + 1)

def write_java(cls, root, tw, th):
    lines = [
        'package dev.afterworld.client.model.gen;', '',
        'import net.minecraft.client.model.geom.PartPose;',
        'import net.minecraft.client.model.geom.builders.CubeDeformation;',
        'import net.minecraft.client.model.geom.builders.CubeListBuilder;',
        'import net.minecraft.client.model.geom.builders.LayerDefinition;',
        'import net.minecraft.client.model.geom.builders.MeshDefinition;',
        'import net.minecraft.client.model.geom.builders.PartDefinition;', '',
        '/** Generated by tools/gen_models.py. Do not edit by hand. */',
        f'public final class {cls} {{',
        f'\tprivate {cls}() {{', '\t}', '',
        '\tpublic static LayerDefinition create() {',
        '\t\tMeshDefinition mesh = new MeshDefinition();',
        '\t\tPartDefinition top = mesh.getRoot();',
    ]
    body = []
    java_part(root, 'top', body, 0)
    lines += body
    lines += [f'\t\treturn LayerDefinition.create(mesh, {tw}, {th});', '\t}', '}', '']
    os.makedirs(JAVA_OUT, exist_ok=True)
    with open(os.path.join(JAVA_OUT, cls + '.java'), 'w') as f:
        f.write('\n'.join(lines))

