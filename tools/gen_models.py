def noise(rng, img, x0, y0, w, h, base, var):
    px = img.load()
    for y in range(y0, y0 + h):
        for x in range(x0, x0 + w):
            d = rng.randint(-var, var)
            px[x, y] = (max(0, min(255, base[0] + d)), max(0, min(255, base[1] + d)), max(0, min(255, base[2] + d)), 255)

def paint_face(img, rng, mat, face, x0, y0, w, h):
    if w <= 0 or h <= 0:
        return
    px = img.load()
    M = MATERIALS[mat]
    M(img, px, rng, face, x0, y0, w, h)

def m_stone(base, moss=0.08, cracks=True):
    def f(img, px, rng, face, x0, y0, w, h):
        b = hexc(base)
        noise(rng, img, x0, y0, w, h, b, 9)
        for _ in range(max(1, w * h // 40)):
            if rng.random() < moss:
                cx, cy = x0 + rng.randrange(w), y0 + rng.randrange(h)
                for dx in range(-1, 2):
                    for dy in range(-1, 1):
                        if x0 <= cx + dx < x0 + w and y0 <= cy + dy < y0 + h and rng.random() < 0.7:
                            px[cx + dx, cy + dy] = shade(hexc('#4E6A3A'), 0.9 + rng.random() * 0.3)
        if cracks and w * h > 30:
            for _ in range(max(1, w * h // 120)):
                cx, cy = x0 + rng.randrange(w), y0 + rng.randrange(h)
                for _ in range(rng.randint(2, 5)):
                    if x0 <= cx < x0 + w and y0 <= cy < y0 + h:
                        px[cx, cy] = shade(b, 0.55)
                    cx += rng.choice((-1, 0, 1))
                    cy += 1
    return f

def m_robe(base):
    def f(img, px, rng, face, x0, y0, w, h):
        b = hexc(base)
        noise(rng, img, x0, y0, w, h, b, 7)
        if face in ('north', 'south', 'east', 'west'):
            for x in range(x0, x0 + w):
                if (x - x0) % 4 == 0:
                    for y in range(y0, y0 + h):
                        px[x, y] = shade(px[x, y], 0.72)
                elif (x - x0) % 4 == 1:
                    for y in range(y0, y0 + h):
                        px[x, y] = shade(px[x, y], 1.12)
            for x in range(x0, x0 + w):
                if rng.random() < 0.4:
                    px[x, y0 + h - 1] = shade(b, 0.55)
        for _ in range(w * h // 50):
            px[x0 + rng.randrange(w), y0 + rng.randrange(h)] = shade(hexc('#4E6A3A'), 1.0)
    return f

def m_hood(img, px, rng, face, x0, y0, w, h):
    m_robe('#6E6A62')(img, px, rng, face, x0, y0, w, h)
    if face == 'north':
        for y in range(y0 + 2, y0 + h):
            for x in range(x0 + 2, x0 + w - 2):
                px[x, y] = (18, 16, 20, 255)
        ey = y0 + h // 2
        for ex in (x0 + w // 2 - 3, x0 + w // 2 + 2):
            px[ex, ey] = hexc('#FFC860')
            px[ex + 1, ey] = hexc('#E8A33D')

def m_wood(img, px, rng, face, x0, y0, w, h):
    noise(rng, img, x0, y0, w, h, hexc('#5A3A24'), 10)
    for y in range(y0, y0 + h):
        if rng.random() < 0.2:
            for x in range(x0, x0 + w):
                px[x, y] = shade(px[x, y], 0.8)

def m_lantern(img, px, rng, face, x0, y0, w, h):
    noise(rng, img, x0, y0, w, h, hexc('#2A2E36'), 4)
    if face in ('north', 'south', 'east', 'west'):
        for y in range(y0 + 1, y0 + h - 1):
            for x in range(x0 + 1, x0 + w - 1):
                t = abs((x - x0) - w / 2) / (w / 2)
                px[x, y] = mix(hexc('#FFF2B0'), hexc('#E8A33D'), t)

def m_tablets(img, px, rng, face, x0, y0, w, h):
    m_stone('#7A766C', moss=0.05)(img, px, rng, face, x0, y0, w, h)
    if face in ('south', 'north'):
        for y in range(y0 + 2, y0 + h - 1, 3):
            for x in range(x0 + 2, x0 + w - 2):
                if rng.random() < 0.65:
                    px[x, y] = shade(hexc('#7A766C'), 0.6)

def m_skin(img, px, rng, face, x0, y0, w, h):
    noise(rng, img, x0, y0, w, h, hexc('#8A9AA0'), 8)
    for _ in range(w * h // 25):
        x, y = x0 + rng.randrange(w), y0 + rng.randrange(h)
        px[x, y] = hexc('#6A7A88')

def m_rags(img, px, rng, face, x0, y0, w, h):
    noise(rng, img, x0, y0, w, h, hexc('#4A3A2A'), 10)
    for x in range(x0, x0 + w):
        if rng.random() < 0.3:
            for y in range(y0, y0 + rng.randint(1, max(1, h // 3))):
                px[x, y] = shade(hexc('#4A3A2A'), 0.7)
    if face == 'north':
        for y in range(y0, y0 + h):
            for x in range(x0 + w // 4, x0 + 3 * w // 4):
                px[x, y] = shade(hexc('#8A9AA0'), 0.9 + rng.random() * 0.1)

def m_sack(img, px, rng, face, x0, y0, w, h):
    noise(rng, img, x0, y0, w, h, hexc('#9C8A62'), 10)
    for y in range(y0, y0 + h, 2):
        for x in range(x0, x0 + w):
            px[x, y] = shade(px[x, y], 0.9)
    if face == 'north':
        cx = x0 + w // 2
        cy = y0 + h // 2 - 1
        for ex in (cx - 3, cx + 2):
            for i in range(-1, 2):
                px[ex + i, cy + i] = (30, 20, 16, 255)
                px[ex + i, cy - i] = (30, 20, 16, 255)
        for x in range(cx - 3, cx + 4):
            if (x - cx) % 2 == 0:
                px[x, cy + 3] = (30, 20, 16, 255)

def m_bronze(img, px, rng, face, x0, y0, w, h):
    noise(rng, img, x0, y0, w, h, hexc('#9C6A2A'), 8)
    for y in range(y0, y0 + h):
        t = (y - y0) / max(1, h - 1)
        for x in range(x0, x0 + w):
            px[x, y] = shade(px[x, y], 1.25 - 0.45 * t)
    for _ in range(w * h // 30):
        px[x0 + rng.randrange(w), y0 + rng.randrange(h)] = hexc('#4FA89B')

def m_chain(img, px, rng, face, x0, y0, w, h):
    for y in range(y0, y0 + h):
        for x in range(x0, x0 + w):
            px[x, y] = hexc('#5A5E66') if (y - y0) % 2 == 0 else hexc('#8A8E96')

def m_brass(img, px, rng, face, x0, y0, w, h):
    noise(rng, img, x0, y0, w, h, hexc('#B8892E'), 7)
    for x in range(x0, x0 + w):
        px[x, y0] = hexc('#F2D27A')
    for y in range(y0, y0 + h):
        if w > 3:
            px[x0, y] = shade(px[x0, y], 0.75)

def m_iron(img, px, rng, face, x0, y0, w, h):
    noise(rng, img, x0, y0, w, h, hexc('#3A3E46'), 6)
    for (x, y) in ((x0, y0), (x0 + w - 1, y0), (x0, y0 + h - 1), (x0 + w - 1, y0 + h - 1)):
        px[x, y] = hexc('#8A8E96')

def m_clockface(img, px, rng, face, x0, y0, w, h):
    m_brass(img, px, rng, face, x0, y0, w, h)
    if face == 'north':
        cx, cy = x0 + (w - 1) / 2, y0 + (h - 1) / 2
        r = min(w, h) / 2 - 1.2
        for y in range(y0, y0 + h):
            for x in range(x0, x0 + w):
                dd = math.hypot(x - cx, y - cy)
                if dd <= r:
                    px[x, y] = hexc('#EDE3CC')
                if r - 0.9 <= dd <= r + 0.3:
                    px[x, y] = hexc('#5A4420')
        for k in range(12):
            a = k * math.pi / 6
            tx, ty = round(cx + math.cos(a) * (r - 1.6)), round(cy + math.sin(a) * (r - 1.6))
            px[tx, ty] = hexc('#1A1A22')

def m_gear(img, px, rng, face, x0, y0, w, h):
    noise(rng, img, x0, y0, w, h, hexc('#3A2E1E'), 5)
    if face in ('north', 'south') and w > 6:
        cx, cy = x0 + (w - 1) / 2, y0 + (h - 1) / 2
        R = min(w, h) / 2 - 0.5
        for y in range(y0, y0 + h):
            for x in range(x0, x0 + w):
                dd = math.hypot(x - cx, y - cy)
                a = math.atan2(y - cy, x - cx)
                tooth = (math.sin(a * 10) > 0.2)
                if dd <= R - 2 or (dd <= R and tooth):
                    px[x, y] = shade(hexc('#B8892E'), 0.9 + 0.2 * rng.random())
                if dd <= R * 0.35:
                    px[x, y] = hexc('#5A4420')
                for k in range(6):
                    sa = k * math.pi / 3
                    if abs(a - sa) < 0.12 and R * 0.35 < dd < R - 2:
                        px[x, y] = hexc('#5A4420')
    else:
        for i in range(x0, x0 + w):
            if (i - x0) % 2 == 0:
                for j in range(y0, y0 + h):
                    px[i, j] = hexc('#B8892E')

def m_kingface(img, px, rng, face, x0, y0, w, h):
    m_brass(img, px, rng, face, x0, y0, w, h)
    if face == 'north':
        cy = y0 + h // 2 - 1
        px[x0 + 3, cy] = hexc('#1A1A22')
        px[x0 + w - 4, cy] = hexc('#4FB3A9')
        px[x0 + w - 4, cy - 1] = hexc('#B8F0E8')
        for x in range(x0 + 2, x0 + w - 2):
            px[x, cy + 3] = hexc('#5A4420')

def m_crown(img, px, rng, face, x0, y0, w, h):
    noise(rng, img, x0, y0, w, h, hexc('#E8B83A'), 6)
    for x in range(x0, x0 + w, 3):
        px[x, y0 + h // 2] = hexc('#C4553B')
        if x + 1 < x0 + w:
            px[x + 1, y0 + h // 2] = hexc('#4FB3A9')

def m_hands(img, px, rng, face, x0, y0, w, h):
    noise(rng, img, x0, y0, w, h, hexc('#1A1A22'), 3)

def m_moss(img, px, rng, face, x0, y0, w, h):
    noise(rng, img, x0, y0, w, h, hexc('#4E6A3A'), 12)

MATERIALS = {
    'stone': m_stone('#7C7A72'), 'robe': m_robe('#77736A'), 'hem': m_stone('#5E5C56', moss=0.3), 'hood': m_hood,
    'sleeve': m_robe('#6E6A62'), 'hand': m_stone('#8C8A82', moss=0.0, cracks=False), 'wood': m_wood, 'lantern': m_lantern,
    'tablets': m_tablets, 'moss': m_moss,
    'skin': m_skin, 'rags': m_rags, 'sack': m_sack, 'bronze': m_bronze, 'chain': m_chain,
    'brass': m_brass, 'iron': m_iron, 'clockface': m_clockface, 'gear': m_gear, 'kingface': m_kingface, 'crown': m_crown, 'hands': m_hands,
}

def paint(root, tw, th, seed):
    img = Image.new('RGBA', (tw, th), (0, 0, 0, 0))
    rng = random.Random(seed)
    for b in all_boxes(root):
        w, h, d = (int(math.ceil(s)) for s in b.size)
        u, v = b.u, b.v
        paint_face(img, rng, b.mat, 'up', u + d, v, w, d)
        paint_face(img, rng, b.mat, 'down', u + d + w, v, w, d)
        paint_face(img, rng, b.mat, 'east', u, v + d, d, h)
        paint_face(img, rng, b.mat, 'north', u + d, v + d, w, h)
        paint_face(img, rng, b.mat, 'west', u + d + w, v + d, d, h)
        paint_face(img, rng, b.mat, 'south', u + d + w + d, v + d, w, h)
    return img

